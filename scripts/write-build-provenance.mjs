#!/usr/bin/env node
/**
 * Embeds git commit + UTC build time for server-side release provenance.
 * Invoked from package.json `prebuild` — no runtime environment variables.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const outPath = resolve(repoRoot, "src/server/build-provenance.generated.ts");

function gitHead() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repoRoot,
      encoding: "utf8",
    }).trim();
  } catch {
    return "unknown";
  }
}

const commit = gitHead();
const builtAt = new Date().toISOString();

const source = `/** Generated by scripts/write-build-provenance.mjs — do not edit. */
export const BUILD_PROVENANCE = {
  commit: ${JSON.stringify(commit)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;
`;

writeFileSync(outPath, source, "utf8");
